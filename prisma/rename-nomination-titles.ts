import "dotenv/config";
import { PrismaPg } from "@prisma/adapter-pg";
import { PrismaClient } from "../lib/generated/prisma/client";

/**
 * Разовый скрипт: добавляет кавычки «…» в названия номинаций, у которых их
 * раньше не было (остальные уже содержат «…» внутри самого названия и не
 * трогаются, чтобы не получить двойные кавычки). Меняет только title —
 * formSchema/criteria/description не затрагиваются.
 */

const RENAMES: { from: string; to: string }[] = [
  {
    from: "Лучший работодатель по трудоустройству несовершеннолетней молодёжи (14–18 лет)",
    to: "«Лучший работодатель по трудоустройству несовершеннолетней молодёжи (14–18 лет)»",
  },
  {
    from: "Лучший работодатель по организации безопасных условий труда для молодёжи",
    to: "«Лучший работодатель по организации безопасных условий труда для молодёжи»",
  },
  {
    from: "Лучшая практика организации деятельности студотрядов в образовательной организации высшего образования",
    to: "«Лучшая практика организации деятельности студотрядов в образовательной организации высшего образования»",
  },
  {
    from: "Лучшая практика организации деятельности студотрядов в профессиональной и общеобразовательной организации",
    to: "«Лучшая практика организации деятельности студотрядов в профессиональной и общеобразовательной организации»",
  },
  { from: "Работа СО смыслом", to: "«Работа СО смыслом»" },
  {
    from: "Лучший орган исполнительной власти по поддержке и развитию студотрядов",
    to: "«Лучший орган исполнительной власти по поддержке и развитию студотрядов»",
  },
  {
    from: "Лучшая практика поддержки трудовых отрядов подростков",
    to: "«Лучшая практика поддержки трудовых отрядов подростков»",
  },
];

const adapter = new PrismaPg({ connectionString: process.env.DATABASE_URL! });
const prisma = new PrismaClient({ adapter });

async function main() {
  for (const r of RENAMES) {
    const nom = await prisma.nomination.findFirst({ where: { title: r.from } });
    if (!nom) {
      // Уже переименована (или не найдена) — пропускаем без ошибки, скрипт идемпотентен.
      const already = await prisma.nomination.findFirst({ where: { title: r.to } });
      console.log(already ? `= уже переименовано: ${r.to}` : `! не найдено: ${r.from}`);
      continue;
    }
    await prisma.nomination.update({ where: { id: nom.id }, data: { title: r.to } });
    console.log(`Переименовано: ${r.from} → ${r.to}`);
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
